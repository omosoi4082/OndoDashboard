/**
 * 기상대 풍속(m/s)을 화면용 값으로 다듬는다 — 단위 환산은 없고 소수 첫째 자리까지만 반올림한다
 * (기상청 `WSD`가 0.1 m/s 단위로 와서 두 패널을 나란히 읽을 수 있게 표기를 맞춘다).
 * null은 그대로 null(결측 유지 — 0으로 채우지 않는다).
 */
export function stationWindMs(raw: number | null): number | null {
  if (raw === null || !Number.isFinite(raw)) return null;
  return Math.round(raw * 10) / 10;
}
